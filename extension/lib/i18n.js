export const LANGUAGES = Object.keys(STRINGS);
let current = 'en';

function detect() {
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return STRINGS[nav] ? nav : 'en';
}

/** `setting` is 'auto' or a language code. */
export function setLanguage(setting) {
  current = setting && setting !== 'auto' && STRINGS[setting] ? setting : detect();
  if (typeof document === 'undefined') return; // service worker: text only
  const root = document.documentElement;
  root.lang = current;
  root.dir = current === 'ar' ? 'rtl' : 'ltr';
}

export const lang = () => current;

export function t(key, vars) {
  const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s;
}

export function applyI18n(root) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) {
    const v = t(el.dataset.i18nAria);
    el.setAttribute('aria-label', v);
    if (el.hasAttribute('title')) el.title = v;
  }
}

